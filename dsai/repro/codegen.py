def _forecast_block(run: Any) -> str:
    best = run.best
    objective = run.objective
    if best is None:
        return ""
    seasonal = best.extras.get("seasonal_period")
    horizon = best.extras.get("horizon", 12)
    return "\n".join([
        "# " + "-" * 74,
        f"# 3. Forecasting: {best.model_name}",
        "# " + "-" * 74,
        f"from dsai.registry.ts_adapters import {_forecaster_class(best.model_key)}",
        "",
        f"TIME_COLUMN = {objective.time_column!r}",
        f"TARGET = {objective.target!r}",
        f"HORIZON = {horizon}",
        f"SEASONAL_PERIOD = {seasonal!r}",
        "",
        "series = (df[[TIME_COLUMN, TARGET]].dropna()",
        "          .assign(**{TIME_COLUMN: lambda d: pd.to_datetime(d[TIME_COLUMN])})",
        "          .sort_values(TIME_COLUMN).set_index(TIME_COLUMN)[TARGET].astype(float))",
        "if series.index.has_duplicates:",
        "    series = series.groupby(level=0).mean()",
        "",
        "# Hold out the last HORIZON periods to check accuracy honestly",
        "train, test = series.iloc[:-HORIZON], series.iloc[-HORIZON:]",
        f"model = {_forecaster_class(best.model_key)}({_format_params(best.hyperparameters or {})})",
        "model.fit(train)",
        "predictions = model.predict(len(test))",
        "",
        "mae = np.mean(np.abs(test.to_numpy() - predictions))",
        "naive = np.mean(np.abs(train.to_numpy()[1:] - train.to_numpy()[:-1]))",
        'print(f"MAE:  {mae:,.2f}")',
        'print(f"MASE: {mae / naive:.3f}  (below 1.0 beats a naive last-value forecast)")',
        "",
        "# Refit on everything and forecast forward",
        f"final = {_forecaster_class(best.model_key)}({_format_params(best.hyperparameters or {})})",
        "final.fit(series)",
        "forecast = final.predict(HORIZON)",
        "print(pd.Series(forecast, name='forecast').round(2).to_string())",
    ])


def _forecaster_class(model_key: str) -> str:
    spec = REGISTRY.get(model_key) if model_key in REGISTRY else None
    path = getattr(spec.builder, "import_path", "") if spec and spec.builder else ""
    return path.partition(":")[2] or "NaiveForecaster"


def _exploratory_block(run: Any) -> str:
    return "\n".join([
        "# " + "-" * 74,
        "# 3. Exploratory analysis",
        "# " + "-" * 74,
        "print(df.describe(include='all').T.to_string())",
        "print(df.isna().sum().sort_values(ascending=False).head(20).to_string())",
        "numeric = df.select_dtypes(include='number')",
        "print(numeric.corr().round(3).to_string())",
    ])


def _footer(run: Any, manifest: Any) -> str:
    lines = [
        "# " + "-" * 74,
        "# Reproducibility notes",
        "# " + "-" * 74,
        f"# Random seed:  {run.settings.random_state}",
        f"# Fingerprint:  {manifest.fingerprint()}",
        "# Environment at the time of the original run:",
    ]
    lines += [f"#   {k}: {v}" for k, v in (run.environment or {}).items()]
    if run.warnings:
        lines += ["#", "# Warnings raised during the original analysis:"]
        lines += [f"#   - {w}" for w in run.warnings[:10]]
    return "\n".join(lines)


def _format_params(params: dict[str, Any]) -> str:
    if not params:
        return ""
    return ", ".join(f"{k}={v!r}" for k, v in params.items())
